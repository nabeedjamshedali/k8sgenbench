def b(s):
    return s.astype(str).str.lower().map({"true": 1, "false": 0})


def cell_bin(s):
    v = b(s).dropna()
    return f"{100 * v.mean():.0f} ({int(v.sum())}/{len(v)})" if len(v) else "--"


def cell_cont(s):
    """(median, interquartile range) cells; the overview tables put the range on its own line under the median,
    so the wide tables fit the text width at full size."""
    v = pd.to_numeric(s, errors="coerce").dropna()
    if not len(v):
        return "--", ""
    return f"{v.median():.1f}", rf"{{\scriptsize[{v.quantile(.25):.1f}, {v.quantile(.75):.1f}]}}"


def write(name, body):
    os.makedirs(OUT, exist_ok=True)
    with open(os.path.join(OUT, name), "w", encoding="utf-8") as f:
        f.write("% generated by evaluation/tables.py -- do not edit\n" + body)
    print(os.path.join(OUT, name))


def overview(df, variant):
    sub = df[(df.prompt_variant == variant) | (df.source == "human")]
    present = [s for s in SOURCES if (sub.source == s).any()]
    cols = "l" + "r" * len(present)
    rows = [" & ".join(["Metric"] + [LABEL[s] for s in present]) + r" \\ \midrule",
            " & ".join(["Configurations"] + [str(int((sub.source == s).sum())) for s in present]) + r" \\ \midrule"]
    rows += [" & ".join([lab] + [cell_bin(sub[sub.source == s][c]) for s in present]) + r" \\" for c, lab in BIN]
    rows.append(r"\midrule")
    for c, lab in CONT:
        cells = [cell_cont(sub[sub.source == s][c]) for s in present]
        rows.append(" & ".join([lab] + [m for m, _ in cells]) + r" \\[-2pt]")
        rows.append(" & ".join([""] + [q for _, q in cells]) + r" \\ \addlinespace[3pt]")
    cap = ("Six-dimension results, %s prompt. Binary rows: percentage (count/n); continuous rows: median "
           "[interquartile range]. The human column is the shipped manifest of each project (one per project). "
           "Continuous rows are computed over the configurations for which the metric is defined: static scores over "
           "parsed configurations, D5 time to Ready and D6 over deployed ones, so their n can be smaller than the column "
           "total. D6 downtime depends mainly on the replica count of the faulted workload "
           "(Section~\\ref{sec:res-rq5}).") % variant
    body = (r"\begin{table*}[t]" "\n" r"\centering\small" "\n" rf"\caption{{{cap}}}\label{{tab:overview-{variant}}}" "\n"
            rf"\begin{{tabular}}{{{cols}}}" "\n" r"\toprule" "\n" + "\n".join(rows) + "\n" r"\bottomrule" "\n"
            r"\end{tabular}" "\n" r"\end{table*}" "\n")
    write(f"tab_overview_{variant}.tex", body)


def failure_reasons(df):
    llm = df[df.source.isin(SOURCES[1:]) & (b(df.d5_ready) == 0)]
    if llm.empty:
        return
    t = llm.groupby(["d5_failure_reason", "prompt_variant"]).size().unstack(fill_value=0)
    t = t.reindex(columns=["neutral", "production"], fill_value=0)
    t["total"] = t.sum(axis=1)
    t = t.sort_values("total", ascending=False)
    rows = [r"Failure class & Neutral & Production & Total \\ \midrule"]
    rows += [f"{str(i).replace('_', ' ')} & {r.neutral} & {r.production} & {r.total} \\\\" for i, r in t.iterrows()]
    body = (r"\begin{table}[t]" "\n" r"\centering\small" "\n"
            r"\caption{Classified reason for LLM-generated configurations that did not become fully Ready (D5), by prompt.}"
            r"\label{tab:d5-failures}" "\n" r"\begin{tabular}{lrrr}" "\n" r"\toprule" "\n" + "\n".join(rows) + "\n"
            r"\bottomrule" "\n" r"\end{tabular}" "\n" r"\end{table}" "\n")
    write("tab_d5_failures.tex", body)


