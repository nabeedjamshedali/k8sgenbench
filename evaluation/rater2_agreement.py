"""Agreement between the root-cause labels (d5_root_causes.csv) and a second, blind labelling pass.

Usage: python evaluation/rater2_agreement.py <answers.csv>
Writes evaluation/analysis/rater2_agreement.md: Cohen's kappa on the category and on the theme (tables.THEMES),
raw agreement, and every disagreement for review.
"""
import os
import sys

import pandas as pd

import tables

HERE = os.path.dirname(os.path.abspath(__file__))
THEME = {c: t for t, items in tables.THEMES for c, _ in items}


def kappa(a, b):
    labels = sorted(set(a) | set(b))
    n = len(a)
    po = sum(x == y for x, y in zip(a, b)) / n
    pe = sum((list(a).count(l) / n) * (list(b).count(l) / n) for l in labels)
    return (po - pe) / (1 - pe), po


def main():
    ans = pd.read_csv(sys.argv[1])
    key = pd.read_csv(os.path.join(HERE, "rater2_key.csv"))
    first = pd.read_csv(os.path.join(HERE, "d5_root_causes.csv"))[["config", "category", "evidence"]]
    d = ans.merge(key, on="case_id").merge(first, on="config", suffixes=("_2", "_1"))
    assert len(d) == len(first) == len(ans), (len(d), len(first), len(ans))
    unknown = sorted(set(d.category_2) - set(THEME))
    assert not unknown, f"unknown categories: {unknown}"
    k_cat, po_cat = kappa(d.category_1, d.category_2)
    k_th, po_th = kappa(d.category_1.map(THEME), d.category_2.map(THEME))
    L = ["# Second-pass root-cause labelling: agreement (generated by evaluation/rater2_agreement.py)\n",
         f"Cases: {len(d)}", f"Category: raw agreement {100 * po_cat:.1f}%, Cohen's kappa {k_cat:.2f}",
         f"Theme: raw agreement {100 * po_th:.1f}%, Cohen's kappa {k_th:.2f}", ""]
    for lvl in ("observed", "inferred", "supported", "undetermined"):
        s = d[d.evidence.str.startswith(lvl)]
        if len(s):
            L.append(f"First-pass evidence level {lvl}: {len(s)} cases, category agreement "
                     f"{100 * (s.category_1 == s.category_2).mean():.0f}%")
    L += ["", "## Disagreements", "", "| case | config | first pass | second pass | second-pass note |", "|---|---|---|---|---|"]
    for _, r in d[d.category_1 != d.category_2].iterrows():
        L.append(f"| {r.case_id} | {r.config} | {r.category_1} | {r.category_2} | {str(r.get('note', ''))[:120]} |")
    out = os.path.join(HERE, "analysis", "rater2_agreement.md")
    open(out, "w", encoding="utf-8").write("\n".join(L) + "\n")
    print("\n".join(L[:9]))


if __name__ == "__main__":
    main()
